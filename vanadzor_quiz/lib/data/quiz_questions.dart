List<QuizQuestion> generateRandomQuizQuestions({Random? random}) {
  final shuffledQuestions = List<QuizQuestion>.of(vanadzorQuestionBank)
    ..shuffle(random);

  return shuffledQuestions
      .take(10)
      .map((question) {
        final shuffledOptions = List<QuizOption>.of(question.options)
          ..shuffle(random);

        return QuizQuestion(
          id: question.id,
          text: question.text,
          options: shuffledOptions,
          correctOptionId: question.correctOptionId,
          didYouKnow: vanadzorQuestionStories[question.id] ?? '',
        );
      })
      .toList(growable: false);
}
